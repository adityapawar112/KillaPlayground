export function getFoliageById(id: string): FoliageItem | undefined {
  return FOLIAGE_MANIFEST.find((item) => item.id === id);
}

export function getFoliageByCategory(category: FoliageCategory): FoliageItem[] {
  return FOLIAGE_MANIFEST.filter((item) => item.category === category);
}

export function searchFoliage(query: string, categoryFilter?: string): FoliageItem[] {
  const q = query.trim().toLowerCase();
  return FOLIAGE_MANIFEST.filter((item) => {
    const matchesCategory =
      !categoryFilter || categoryFilter === 'all' || item.category === categoryFilter;
    if (!matchesCategory) return false;
    if (!q) return true;
    return (
      item.name.toLowerCase().includes(q) ||
      item.category.toLowerCase().includes(q) ||
      (item.culturalLore && item.culturalLore.toLowerCase().includes(q))
    );
  });
}
